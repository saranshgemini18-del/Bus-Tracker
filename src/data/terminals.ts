  id: s.id,
  name: s.name,
  type: s.type || 'Bus Stand',
  lat: s.lat,
  lng: s.lng,
  zone: s.zone || 'Delhi NCR',
  description: `Official DTC Bus Stand • Code: ${s.stopCode || s.id} • ${s.zone || 'Delhi'}`,
  majorRoutes: s.majorRoutes || [],
